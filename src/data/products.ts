export const products: Product[] = drafts.map((draft, index) => {
  const { reviewSeed, reviewSampleCount, ...rest } = draft
  return {
    ...rest,
    id: `p-${index + 1}`,
    currency: 'PKR',
    reviews: makeReviews(reviewSeed, reviewSampleCount ?? 1),
  }
})

export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug)
}

export function getRelatedProducts(product: Product, limit = 4) {
  return products
    .filter((p) => p.id !== product.id && p.category === product.category)
    .slice(0, limit)
}

export const featuredProducts = products.filter((p) => p.featured)
export const bestSellerProducts = products.filter((p) => p.bestSeller)
export const newArrivalProducts = products.filter((p) => p.isNew)
