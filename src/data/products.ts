function makeReviews(seed: number, count: number): ProductReview[] {
  const list: ProductReview[] = []
  for (let i = 0; i < count; i++) {
    const base = reviewPool[(seed + i) % reviewPool.length]
    list.push({ ...base, id: `rev-${seed}-${i}` })
  }
  return list
}

